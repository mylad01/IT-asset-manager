// Pre-paint boot — PLAN.MD §13. The SINGLE SOURCE for the inline script
// that runs in index.html <head> BEFORE any module loads (FOUC guard), and
// for the constants the module-side appliers (src/config/applyPreferences)
// use for the exact same effects.
//
// Why this exists: the inline boot must be duplicated into the HTML on
// purpose (it cannot be a module — it must run before main.jsx). Previously
// the mode/tier maps were hand-copied into index.html and hand-mirrored in
// applyPreferences, guarded only by tests that string-matched the copies.
// Now the script is GENERATED here from registry data; a Vite plugin
// (vite.config.js, prePaintInject) injects it into index.html for both the
// dev server and the build, and scripts/testPreferencesRegistry.js executes
// THE GENERATED SCRIPT in a vm. A behavior change or a registry edit that
// breaks first paint now fails the sync test — the copies cannot drift
// because there are no copies left.
//
// Layering: imports from ./preferencesRegistry.js (same tree). index.html is
// transformed by vite.config.js (root-level, tooling context — allowed);
// the browser only ever sees the generated string.

import { THEME_PRESETS, GLASS_LEVELS, ACCENT_PALETTE, DECOR_LEVELS } from './preferencesRegistry.js';

/** localStorage key for the full prefs blob (must match applyPreferences). */
export const PREFS_STORAGE_KEY = 'studioUiPrefs';

/** theme value → brightness class. DERIVED from the registry, never copied. */
export const THEME_MODES = Object.fromEntries(THEME_PRESETS.map((t) => [t.value, t.mode]));

/** accent value → oklch per brightness class. DERIVED from ACCENT_PALETTE. */
export const ACCENT_COLORS = Object.fromEntries(
  ACCENT_PALETTE.map((a) => [a.value, { dark: a.dark, light: a.light }]),
);

/**
 * Glass tier → CSS var overrides, data-driven from GLASS_LEVELS:
 *  - crystal (first entry, heaviest) = the stylesheet's heavy defaults;
 *  - frosted (a LIGHT tier) gets the reduced-blur values;
 *  - balanced = NO inline vars (CSS defaults must stand).
 * The `vars` field carries the blur values; the sync test asserts these
 * are the ONLY blur/rgba literals the appliers write.
 */
export const GLASS_VAR_TIERS = Object.fromEntries(GLASS_LEVELS.map((g) => {
  if (g.value === 'crystal') {
    return [g.value, {
      '--glass-blur': 'blur(20px) saturate(180%)',
      '--glass-blur-heavy': 'blur(40px) saturate(200%)',
      '--glass-bg': 'rgba(255, 255, 255, 0.18)',
    }];
  }
  if (g.value === 'frosted') {
    return [g.value, {
      '--glass-blur': 'blur(10px) saturate(140%)',
      '--glass-blur-heavy': 'blur(20px) saturate(160%)',
      '--glass-bg': 'rgba(255, 255, 255, 0.12)',
    }];
  }
  return [g.value, null]; // balanced → CSS defaults
}));

/**
 * Non-enum document-level prefs (PLAN.MD §13 P2/P3), expressed as data so
 * the generated pre-paint script and the module appliers behave
 * identically. `attr` = <html> attribute name; `default` = the registry
 * default; `on`/`off` = literal values written (booleans serialize as
 * 'on'/'off', enums write their own value — those live in ATTR_VALUE_ENUMS
 * below).
 */
export const BOOL_ATTRS = {
  performanceMode: { attr: 'data-performance', on: 'on', off: 'off' },
  reducedTransparency: { attr: 'data-reduced-transparency', on: 'on', off: 'off' },
  alwaysFocusRings: { attr: 'data-focus-rings', on: 'on', off: 'off' },
  largerTouchTargets: { attr: 'data-touch-targets', on: 'on', off: 'off' },
};

/** Enum-valued attrs: value written as-is, with a safe default. */
export const ATTR_VALUE_ENUMS = {
  density: { attr: 'data-density', values: ['compact', 'comfortable', 'spacious'], fallback: 'comfortable' },
  motion: { attr: 'data-motion', values: ['full', 'reduced', 'off'], fallback: 'full' },
  accent: { attr: 'data-accent', values: ACCENT_PALETTE.map((a) => a.value), fallback: 'default' },
  decor: { attr: 'data-decor', values: DECOR_LEVELS.map((d) => d.value), fallback: 'none' },
};

/**
 * Clamp for fontScale (an INT pref): inline style font-size percentage.
 * Derived loosely here (85–125 mirrors the registry's min/max) — the sync
 * test asserts parity with the registry bounds.
 */
export const FONT_SCALE = { min: 85, max: 125, fallback: 100 };

const JSON_SAFE = (v) => JSON.stringify(v);

/**
 * Generate the inline pre-paint script (ES5 only — runs before any
 * transpilation). Both index.html (via the Vite plugin) and the sync
 * test's vm harness execute EXACTLY this text.
 */
export function generatePrePaintScript() {
  return `/* Generated by shared/prePaintScript.js — DO NOT EDIT the injected copy.
   Source of truth: shared/prePaintScript.js + preferencesRegistry.js
   (vite plugin prePaintInject injects this at build/dev time). */
(function() {
  var doc = document.documentElement;
  if (!doc.setAttribute) return;
  var prefs = null;
  try { prefs = JSON.parse(localStorage.getItem(${JSON_SAFE(PREFS_STORAGE_KEY)}) || 'null'); } catch (e) { prefs = null; }
  if (!prefs || typeof prefs !== 'object' || Array.isArray(prefs)) prefs = {};

  var modes = ${JSON_SAFE(THEME_MODES)};
  var t = prefs.theme || 'dark';
  doc.setAttribute('data-theme', t);
  var brightness = modes[t] || 'dark';
  doc.setAttribute('data-brightness', brightness);
  doc.setAttribute('data-glass', prefs.glass || 'balanced');

  // Accent — data-accent for CSS + --accent inline var for the ACTIVE
  // brightness class (native accent-color consumes the var).
  var accents = ${JSON_SAFE(ACCENT_COLORS)};
  var a = accents[prefs.accent] ? prefs.accent : 'default';
  doc.setAttribute('data-accent', a);
  doc.style.setProperty('--accent', accents[a][brightness] || accents[a].dark);

  // Enum attrs — written as-is when the stored value is a known enum member.
  var enums = ${JSON_SAFE(ATTR_VALUE_ENUMS)};
  var enumKeys = Object.keys(enums);
  for (var e = 0; e < enumKeys.length; e++) {
    var spec = enums[enumKeys[e]];
    var v = prefs[enumKeys[e]];
    doc.setAttribute(spec.attr, spec.values.indexOf(v) >= 0 ? v : spec.fallback);
  }

  // Boolean attrs — 'on'/'off' literals, matching the module appliers.
  var bools = ${JSON_SAFE(BOOL_ATTRS)};
  var boolKeys = Object.keys(bools);
  for (var b = 0; b < boolKeys.length; b++) {
    var bspec = bools[boolKeys[b]];
    doc.setAttribute(bspec.attr, prefs[boolKeys[b]] === true ? bspec.on : bspec.off);
  }

  // Font scale — inline percentage (85–125 clamp mirrors the registry).
  var fsMin = ${JSON_SAFE(FONT_SCALE.min)};
  var fsMax = ${JSON_SAFE(FONT_SCALE.max)};
  var fs = Number(prefs.fontScale);
  if (!isFinite(fs)) fs = ${JSON_SAFE(FONT_SCALE.fallback)};
  if (fs < fsMin) fs = fsMin;
  if (fs > fsMax) fs = fsMax;
  doc.style.fontSize = fs + '%';

  var tiers = ${JSON_SAFE(Object.fromEntries(Object.entries(GLASS_VAR_TIERS).filter(([, v]) => v)))};
  var tier = tiers[prefs.glass];
  if (tier) {
    var vars = Object.keys(tier);
    for (var i = 0; i < vars.length; i++) doc.style.setProperty(vars[i], tier[vars[i]]);
  }
})();`;
}
